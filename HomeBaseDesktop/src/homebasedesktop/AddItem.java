    private void saveItemBtnClicked(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveItemBtnClicked
        // TODO add your handling code here:
        String message = "";
        if (itemName.getText().trim().isEmpty()) {
            message = "Item name cannot be empty!";
            System.out.println(message);
        } 
        
        
        else {
            String itemDateStr = itemDate.getText().trim();
            String itemNameStr = itemName.getText().trim();
            String locationStr = (String) itemLocation.getSelectedItem();
            String categoryStr = (String) ItemCategory.getSelectedItem();
            
            

            int locationId = Integer.parseInt(locationStr.split(" - ")[0]);
            int categoryId = Integer.parseInt(categoryStr.split(" - ")[0]);
            
            System.out.println("*********** Add Item ****************");
            System.out.println("Date: " + itemDate.getText());
            System.out.println("Name: " + itemName.getText());
            System.out.println("Location: " + locationStr);
            System.out.println("Category: " + categoryStr);
            System.out.println("Cost: " + itemCost.getValue());
            System.out.println("Quantity: " + itemQuantity.getValue());
            System.out.println("Note: " + itemNote.getText());
            System.out.println("Image url: " + itemImageUrl.getText());
            System.out.println("*************************************");
            
            EntityManagerFactory emf = Persistence.createEntityManagerFactory("HomeBaseDesktopPU");
            EntityManager em = emf.createEntityManager();
            
            try {
                // make sure required fields: name, date, location, and category is not empty
                HomeBaseFieldRules fieldRule = new HomeBaseFieldRules();
                java.util.Map<String, String> requiredFields = new java.util.HashMap<>();
                requiredFields.put("Item date", itemDateStr);
                requiredFields.put("Item name", itemNameStr);
                requiredFields.put("Location", locationStr);
                requiredFields.put("Category", categoryStr);
                fieldRule.testRequiredField(requiredFields);

                // test the date format and make sure its not set to future
                HomeBaseDateRules dateRule = new HomeBaseDateRules();
                dateRule.testItemDate(itemDate.getText());

                // check the price and quantity
                HomeBasePriceRules priceRule = new HomeBasePriceRules();
                priceRule.testItemPrice((Integer) itemCost.getValue());

                HomeBaseQuantityRules quantityRule = new HomeBaseQuantityRules();

                quantityRule.testItemQuantity((Integer) itemQuantity.getValue());

                Item item = new Item();
                item.setDate(itemDate.getText());
                item.setName(itemName.getText());
                
                Location location = em.find(Location.class, locationId);
                Category category = em.find(Category.class, categoryId);
                
                item.setLocationId(location);
                item.setCategoryId(category);
                item.setCost((Integer) itemCost.getValue());
                item.setQuantity((Integer) itemQuantity.getValue());
                item.setNote(itemNote.getText());
                item.setUrlPath(itemImageUrl.getText());
               
                em.getTransaction().begin();
                em.persist(item);
                em.getTransaction().commit();
                em.close();
                emf.close();

                message = "Item saved successfully!";
            } catch (Exception ex) {
                message = ex.getMessage();
            }
        }

        msgLabel.setText(message);
        msgLabel.setVisible(true);
        
        Timer timer = new Timer(5000, e -> {
            msgLabel.setVisible(false);
        });
        timer.setRepeats(false);
        timer.start();
    }//GEN-LAST:event_saveItemBtnClicked

