    private void loadCategoriesFromDb() {
        EntityManagerFactory emf = Persistence.createEntityManagerFactory("HomeBaseDesktopPU");
        EntityManager em = emf.createEntityManager();
        
        try {
            List<Category> categories = em.createQuery("SELECT category FROM Category category", Category.class).getResultList();
            ItemCategory.removeAllItems();
            
            for (Category c : categories) {
                ItemCategory.addItem(c.getCategoryId() + " - " + c.getName());
            }
            
            em.close();
            emf.close();
        } catch (Exception ex) {
            System.out.println("Error loading categories in Item form");
        } 
    }
    
    private void loadLocationsFromDb() {
        EntityManagerFactory emf = Persistence.createEntityManagerFactory("HomeBaseDesktopPU");
        EntityManager em = emf.createEntityManager();
        
        try {
            List<Location> locations = em.createQuery("SELECT location FROM Location location", Location.class).getResultList();
            itemLocation.removeAllItems();
            
            for (Location location : locations) {
                itemLocation.addItem(location.getLocationId() + " - " + location.getName());
            }
            
            em.close();
            emf.close();
        } catch (Exception ex) {
            System.out.println("Error loading location in Item form");
        } 
    }

